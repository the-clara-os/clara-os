#!/usr/bin/env python3
"""Turn the printable ASCII range of an 8x16 BDF bitmap font into kernel/font.c.

usage: tools/bdf2c.py <font.bdf> <license.txt> <out.c>      (or: make font)
"""
import sys

FIRST, LAST = 0x20, 0x7E  # printable ASCII; every other character draws as a box
WIDTH, HEIGHT = 8, 16
BOX = [0x00] * 2 + [0x7E] + [0x42] * 8 + [0x7E] + [0x00] * 4  # sits on the baseline


def parse(path):
    """Return the font bounding box and {code point: (glyph box, bitmap rows)}."""
    box, glyphs = None, {}
    code = bbx = rows = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            words = line.split()
            if not words:
                continue
            if rows is not None and words[0] != "ENDCHAR":
                rows.append(int(words[0], 16))
            elif words[0] == "FONTBOUNDINGBOX":
                box = tuple(int(w) for w in words[1:5])
            elif words[0] == "ENCODING":
                code = int(words[1])
            elif words[0] == "BBX":
                bbx = tuple(int(w) for w in words[1:5])
            elif words[0] == "BITMAP":
                rows = []
            elif words[0] == "ENDCHAR":
                glyphs[code] = (bbx, rows)
                rows = None
    return box, glyphs


def cell(box, bbx, rows):
    """Place a glyph's bitmap in the font's cell: one byte per scanline, leftmost pixel in bit 7."""
    _, height, box_x, box_y = box
    glyph_w, glyph_h, glyph_x, glyph_y = bbx
    if glyph_w > WIDTH:
        sys.exit("glyph wider than the cell")
    top = (height + box_y) - (glyph_h + glyph_y)  # empty scanlines above the glyph
    out = [0] * height
    for i, bits in enumerate(rows):
        out[top + i] = (bits >> (glyph_x - box_x)) & 0xFF
    return out


def row(label, scanlines):
    return "    /* %-8s */ { %s }," % (label, ", ".join(f"0x{b:02x}" for b in scanlines))


def main(bdf_path, license_path, out_path):
    box, glyphs = parse(bdf_path)
    if box is None or box[:2] != (WIDTH, HEIGHT):
        sys.exit(f"{bdf_path}: expected an {WIDTH}x{HEIGHT} font, found {box}")
    with open(license_path, encoding="utf-8") as f:
        license_lines = f.read().strip().splitlines()

    out = [
        f"/* Generated by tools/bdf2c.py from {bdf_path}. Do not edit: run `make font`.",
        " *",
        " * The glyphs come from the Spleen font, distributed under this license:",
        " *",
    ]
    out += [f" * {line}".rstrip() for line in license_lines]
    out += [
        " */",
        '#include "kernel.h"',
        "",
        f"_Static_assert(FONT_WIDTH == {WIDTH} && FONT_HEIGHT == {HEIGHT},"
        f' "font.c holds {WIDTH}x{HEIGHT} glyphs");',
        "",
        "/* One byte per scanline, leftmost pixel in bit 7: printable ASCII, then a",
        " * box that stands for every other character. */",
        f"static const uint8_t glyphs[{LAST - FIRST + 2}][FONT_HEIGHT] = {{",
    ]
    for code in range(FIRST, LAST + 1):
        if code not in glyphs:
            sys.exit(f"{bdf_path}: no glyph for U+{code:04X}")
        out.append(row(f"0x{code:02x} {chr(code)}", cell(box, *glyphs[code])))
    out.append(row("the rest", BOX))
    out += [
        "};",
        "",
        "const uint8_t *font_glyph(char c)",
        "{",
        "    uint8_t code = (uint8_t)c;",
        "",
        f"    return glyphs[code >= 0x{FIRST:02x} && code <= 0x{LAST:02x}"
        f" ? code - 0x{FIRST:02x} : {LAST - FIRST + 1}];",
        "}",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
